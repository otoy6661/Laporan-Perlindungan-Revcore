$ErrorActionPreference='Stop'
$root='C:\Users\Lord Otoy\Documents\REVCORE_BE10_RESEARCH'
$manifest=Join-Path $root 'REPORTS\BE10_SHA256_MANIFEST.csv'
$existing=@{}
Import-Csv $manifest | ForEach-Object { $existing[$_.RelPath]=$true }

$targets=@()
$targets += Get-ChildItem (Join-Path $root 'EXTRACTED_ARCHIVES') -Recurse -File -ErrorAction SilentlyContinue
$targets += Get-ChildItem (Join-Path $root 'ANALYSIS') -File -ErrorAction SilentlyContinue
$targets += Get-ChildItem (Join-Path $root 'PROTOTYPES\RESULTS') -File -ErrorAction SilentlyContinue
$targets += Get-ChildItem (Join-Path $root 'REPORTS') -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne 'BE10_SHA256_MANIFEST.csv' }
$targets += Get-ChildItem $root -File -Filter 'BE10_*.md' -ErrorAction SilentlyContinue
$targets += Get-ChildItem $root -File -Filter 'README.md' -ErrorAction SilentlyContinue
$targets += Get-Item (Join-Path $root 'SOURCES\ADX_D2_TECH\ARCHIVE\ADX KEIHIN BE.7z') -ErrorAction SilentlyContinue

$added=0
foreach($f in $targets){
  $rel=$f.FullName.Substring($root.Length+1).Replace('/','\')
  if($existing.ContainsKey($rel)){ continue }
  $hash=(Get-FileHash $f.FullName -Algorithm SHA256).Hash.ToLower()
  $cat='ARTIFACT'
  if($rel -like 'ANALYSIS\*'){ $cat='ANALYSIS_EVIDENCE' }
  elseif($rel -like 'PROTOTYPES\RESULTS\*'){ $cat='PROTOTYPE_RESULT' }
  elseif($rel -like 'REPORTS\*'){ $cat='REPORT_DELIVERABLE' }
  elseif($rel -like 'EXTRACTED_ARCHIVES\*'){ $cat='EXTRACTED_ARCHIVE' }
  elseif($rel -like 'SOURCES\ADX_D2_TECH\ARCHIVE\*'){ $cat='ADX_ARCHIVE_SOURCE' }
  elseif($rel -like 'BE10_*.md' -or $rel -eq 'README.md'){ $cat='REPORT_DELIVERABLE' }
  $prov='Generated by BE-10 research; immutable source elsewhere in workspace'
  if($cat -eq 'ADX_ARCHIVE_SOURCE'){ $prov='Copied unmodified from Downloads REMAP TOOLS BE-09 Revisi 3\FILE BIN XDF ADX' }
  $line='"{0}","{1}",{2},"{3}","{4}"' -f $cat,$prov,$f.Length,$rel,$hash
  Add-Content -Path $manifest -Value $line -Encoding UTF8
  $added++
}
$count=(Get-Content $manifest | Measure-Object -Line).Lines
Write-Output "ADDED=$added TOTAL_LINES=$count"
